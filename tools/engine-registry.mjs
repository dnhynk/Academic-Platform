// Renders the generated half of the deterministic engine registry.
//
// `schemas/registry/engine-registry-v1.json` is the single source of truth for
// the thirteen §28 engines. This module turns it into the Rust constants in
// `crates/domain/src/engines/generated.rs`. `pnpm verify:contracts` renders
// again and compares byte-for-byte, so neither side can be edited alone.
//
//   node tools/engine-registry.mjs --write
//
// rewrites the generated module after a registry change.

import { readFile, writeFile } from "node:fs/promises";

export const REGISTRY_PATH = "schemas/registry/engine-registry-v1.json";
export const GENERATED_PATH = "crates/domain/src/engines/generated.rs";

/** Reads and parses the registry source file. */
export async function readRegistry(root = ".") {
  return JSON.parse(await readFile(`${root}/${REGISTRY_PATH}`, "utf8"));
}

/** Converts a SCREAMING_SNAKE_CASE name into its Rust variant identifier. */
export function variant(name) {
  return name
    .split("_")
    .map((word) => `${word.slice(0, 1)}${word.slice(1).toLowerCase()}`)
    .join("");
}

/** Derives the stable engine identifier for a registry name. */
export function engineId(name) {
  return `engine.${name.toLowerCase().replaceAll("_", ".")}`;
}

/** Derives the registry name a §28 table engine cell must carry. */
export function specName(cell) {
  return cell
    .toUpperCase()
    .replaceAll(/[^A-Z0-9]+/gu, "_")
    .replaceAll(/^_|_$/gu, "");
}

function quote(value) {
  return JSON.stringify(value);
}

function optional(value, render) {
  return value === null ? "None" : `Some(${render(value)})`;
}

function specRow(row) {
  return [
    "SpecRow {",
    `        engine: ${quote(row.engine)},`,
    `        inputs: ${quote(row.inputs)},`,
    `        outputs: ${quote(row.outputs)},`,
    `        invariant: ${quote(row.invariant)},`,
    "    }",
  ].join("\n");
}

function descriptorLines(entry) {
  return [
    "EngineDescriptor {",
    `    name: EngineName::${variant(entry.name)},`,
    `    engine_id: ${quote(entry.engine_id)},`,
    `    requirement_id: ${quote(entry.requirement_id)},`,
    `    since_registry_version: ${entry.since_registry_version},`,
    `    spec_row: ${optional(entry.spec_row, specRow)},`,
    `    spec_sentence: ${optional(entry.spec_sentence, quote)},`,
    `    high_impact_path: ${optional(
      entry.high_impact_path,
      (value) => `HighImpactPath::${variant(value)}`,
    )},`,
    `    lifecycle: EngineLifecycle::${variant(entry.lifecycle)},`,
    `    harness_dir: ${quote(entry.harness_dir)},`,
    "}",
  ];
}

function indent(lines, depth) {
  const pad = " ".repeat(depth);
  return lines.map((line) => (line.length === 0 ? line : `${pad}${line}`));
}

function comma(lines) {
  return lines.map((line, index) => (index === lines.length - 1 ? `${line},` : line));
}

/** Renders the whole generated module for a parsed registry. */
export function renderRustModule(registry) {
  const names = registry.engines.map((entry) => entry.name);
  const lines = [
    "// @generated by tools/engine-registry.mjs from",
    `// ${REGISTRY_PATH}. Do not edit by hand: \`pnpm verify:contracts\` renders`,
    "// this file again and rejects any difference.",
    "",
    "use super::{EngineDescriptor, EngineLifecycle, HighImpactPath};",
    "",
    "/// Version of the engine registry these constants were rendered from.",
    `pub const ENGINE_REGISTRY_VERSION: u16 = ${registry.registry_version};`,
    "",
    "/// Repository-relative root every engine's harness artifacts live under.",
    `pub const HARNESS_ROOT: &str = ${quote(registry.harness_root)};`,
    "",
    "/// The §28 table row an engine is registered from, quoted verbatim.",
    "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
    "pub struct SpecRow {",
    "    /// The `Engine` cell.",
    "    pub engine: &'static str,",
    "    /// The `입력` cell.",
    "    pub inputs: &'static str,",
    "    /// The `출력` cell.",
    "    pub outputs: &'static str,",
    "    /// The `핵심 불변조건` cell.",
    "    pub invariant: &'static str,",
    "}",
    "",
    "/// The thirteen §28 engines, in specification order.",
    "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]",
    "pub enum EngineName {",
    ...registry.engines.flatMap((entry) => [
      `    /// \`${entry.name}\`: ${entry.requirement_id}.`,
      `    ${variant(entry.name)},`,
    ]),
    "}",
    "",
    "impl EngineName {",
    "    /// Every registered engine, in specification order.",
    `    pub const ALL: [Self; ${names.length}] = [`,
    ...names.map((name) => `        Self::${variant(name)},`),
    "    ];",
    "",
    "    /// Returns the registry name of the engine.",
    "    #[must_use]",
    "    pub const fn as_str(self) -> &'static str {",
    "        match self {",
    ...names.map((name) => `            Self::${variant(name)} => ${quote(name)},`),
    "        }",
    "    }",
    "",
    "    /// Resolves a registry name, or `None` when it is not registered.",
    "    #[must_use]",
    "    pub fn parse(name: &str) -> Option<Self> {",
    "        Self::ALL.into_iter().find(|value| value.as_str() == name)",
    "    }",
    "",
    "    /// Returns everything the registry fixes about this engine.",
    "    #[must_use]",
    "    pub const fn descriptor(self) -> &'static EngineDescriptor {",
    "        &ENGINE_REGISTRY[self as usize]",
    "    }",
    "}",
    "",
    "/// The registry itself, indexed by [`EngineName`].",
    "///",
    "/// The layout below is the generator's, not rustfmt's, so that a byte",
    "/// comparison against a fresh render is the whole drift check.",
    "#[rustfmt::skip]",
    `pub const ENGINE_REGISTRY: [EngineDescriptor; ${names.length}] = [`,
    ...registry.engines.flatMap((entry) => comma(indent(descriptorLines(entry), 4))),
    "];",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[2] === "--write") {
  const registry = await readRegistry();
  await writeFile(GENERATED_PATH, renderRustModule(registry), "utf8");
}
