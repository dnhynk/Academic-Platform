// Renders the generated half of the predicate registry from its source file.
//
// `schemas/registry/predicate-registry-v1.json` is the single source of truth
// for the twenty §7.2 edges. This module turns it into the Rust constants in
// `crates/domain/src/predicates/generated.rs`. `pnpm verify:contracts` renders
// again and compares byte-for-byte, so neither side can be edited alone.
//
//   node tools/predicate-registry.mjs --write
//
// rewrites the generated module after a registry change.

import { readFile, writeFile } from "node:fs/promises";

export const REGISTRY_PATH = "schemas/registry/predicate-registry-v1.json";
export const GENERATED_PATH = "crates/domain/src/predicates/generated.rs";

/** Reads and parses the registry source file. */
export async function readRegistry(root = ".") {
  return JSON.parse(await readFile(`${root}/${REGISTRY_PATH}`, "utf8"));
}

/** Converts a SCREAMING_SNAKE_CASE name into its Rust variant identifier. */
export function variant(name) {
  return name
    .split("_")
    .map((word) => `${word.slice(0, 1)}${word.slice(1).toLowerCase()}`)
    .join("");
}

/** Derives the stable claim predicate identifier for an edge name. */
export function predicateId(name) {
  return `graph.${name.toLowerCase().replaceAll("_", ".")}`;
}

function quote(value) {
  return JSON.stringify(value);
}

function list(items) {
  return `&[${items.join(", ")}]`;
}

function indent(lines, depth) {
  const pad = " ".repeat(depth);
  return lines.map((line) => (line.length === 0 ? line : `${pad}${line}`));
}

function comma(lines) {
  return lines.map((line, index) => (index === lines.length - 1 ? `${line},` : line));
}

function evidenceLines(rule, label) {
  return [
    `${label}MinimumEvidence {`,
    `    supporting: ${rule.supporting},`,
    `    independent_sources: ${rule.independent_sources},`,
    `    min_strength: EvidenceStrength::${variant(rule.min_strength)},`,
    `    authority: ${list(rule.authority.map((value) => `AuthorityClass::${variant(value)}`))},`,
    `    locator_kinds: ${list(
      rule.locator_kinds.map((value) => `EvidenceLocatorKind::${variant(value)}`),
    )},`,
    "}",
  ];
}

function qualifierLines(schema) {
  const kind =
    schema.kind === "ENUMERATION"
      ? `QualifierKind::Enumeration(${list(schema.values.map(quote))})`
      : `QualifierKind::${variant(schema.kind)}`;
  return [
    "QualifierSchema {",
    `    key: ${quote(schema.key)},`,
    `    kind: ${kind},`,
    `    required: ${schema.required},`,
    "}",
  ];
}

function overrideLines(override) {
  return [
    "(",
    `    PrerequisiteStrength::${variant(override.strength)},`,
    ...comma(indent(evidenceLines(override.rule, ""), 4)),
    ")",
  ];
}

function descriptorLines(entry) {
  const rule = entry.minimum_evidence;
  const qualifiers = entry.qualifiers.flatMap((schema) =>
    comma(indent(qualifierLines(schema), 8)),
  );
  const overrides = rule.by_strength.flatMap((override) =>
    comma(indent(overrideLines(override), 12)),
  );
  const ceiling =
    entry.personal_state_ceiling === null
      ? "None"
      : `Some(MasteryLevel::${variant(entry.personal_state_ceiling)})`;

  return [
    "PredicateDescriptor {",
    `    name: PredicateName::${variant(entry.name)},`,
    `    predicate_id: ${quote(entry.predicate_id)},`,
    `    since_registry_version: ${entry.since_registry_version},`,
    `    spec_direction: ${quote(entry.spec_direction)},`,
    `    spec_meaning: ${quote(entry.spec_meaning)},`,
    `    direction: EdgeDirection::${variant(entry.direction)},`,
    `    cardinality: Cardinality::${variant(entry.cardinality)},`,
    `    subject_types: ${list(entry.subject_types.map((value) => `NodeType::${variant(value)}`))},`,
    `    object_types: ${list(entry.object_types.map((value) => `NodeType::${variant(value)}`))},`,
    `    prerequisite: ${entry.prerequisite},`,
    `    strengths: ${list(
      entry.strengths.map((value) => `PrerequisiteStrength::${variant(value)}`),
    )},`,
    `    personal_state_ceiling: ${ceiling},`,
    `    inverse_label: ${quote(entry.inverse_label)},`,
    ...(qualifiers.length === 0
      ? ["    qualifiers: &[],"]
      : ["    qualifiers: &[", ...qualifiers, "    ],"]),
    "    minimum_evidence: EvidenceRule {",
    ...comma(indent(evidenceLines(rule.base, "base: "), 8)),
    ...(overrides.length === 0
      ? ["        by_strength: &[],"]
      : ["        by_strength: &[", ...overrides, "        ],"]),
    "    },",
    "}",
  ];
}

/** Renders the whole generated module for a parsed registry. */
export function renderRustModule(registry) {
  const names = registry.predicates.map((entry) => entry.name);
  const lines = [
    "// @generated by tools/predicate-registry.mjs from",
    `// ${REGISTRY_PATH}. Do not edit by hand: \`pnpm verify:contracts\` renders`,
    "// this file again and rejects any difference.",
    "",
    "use super::{",
    "    Cardinality, EdgeDirection, EvidenceLocatorKind, EvidenceRule, MinimumEvidence,",
    "    PredicateDescriptor, PrerequisiteStrength, QualifierKind, QualifierSchema,",
    "};",
    "use crate::{AuthorityClass, EvidenceStrength, MasteryLevel};",
    "",
    "/// Version of the predicate registry these constants were rendered from.",
    `pub const PREDICATE_REGISTRY_VERSION: u16 = ${registry.registry_version};`,
    "",
    "/// §38 gates this registry deliberately leaves open.",
    "///",
    "/// The base taxonomy mix is versioned configuration with no default: the",
    "/// registry names predicates and seeds no concept, field, or competency.",
    `pub const OPEN_GATES: [&str; ${registry.open_gates.length}] = [${registry.open_gates
      .map(quote)
      .join(", ")}];`,
    "",
    "/// Node types admitted at either end of an edge, from the §7.1 hierarchy.",
    "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]",
    "pub enum NodeType {",
    ...registry.node_types.flatMap((name) => [`    /// \`${name}\`.`, `    ${variant(name)},`]),
    "}",
    "",
    "impl NodeType {",
    "    /// Every §7.1 node type, in specification order.",
    `    pub const ALL: [Self; ${registry.node_types.length}] = [`,
    ...registry.node_types.map((name) => `        Self::${variant(name)},`),
    "    ];",
    "",
    "    /// Returns the registry spelling of the node type.",
    "    #[must_use]",
    "    pub const fn as_str(self) -> &'static str {",
    "        match self {",
    ...registry.node_types.map((name) => `            Self::${variant(name)} => ${quote(name)},`),
    "        }",
    "    }",
    "}",
    "",
    "/// The twenty §7.2 edges, in specification order.",
    "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]",
    "pub enum PredicateName {",
    ...registry.predicates.flatMap((entry) => [
      `    /// \`${entry.name}\`: ${entry.spec_direction}`,
      `    ${variant(entry.name)},`,
    ]),
    "}",
    "",
    "impl PredicateName {",
    "    /// Every registered predicate, in specification order.",
    `    pub const ALL: [Self; ${names.length}] = [`,
    ...names.map((name) => `        Self::${variant(name)},`),
    "    ];",
    "",
    "    /// Returns the registry name of the predicate.",
    "    #[must_use]",
    "    pub const fn as_str(self) -> &'static str {",
    "        match self {",
    ...names.map((name) => `            Self::${variant(name)} => ${quote(name)},`),
    "        }",
    "    }",
    "",
    "    /// Resolves a registry name, or `None` when it is not registered.",
    "    #[must_use]",
    "    pub fn parse(name: &str) -> Option<Self> {",
    "        Self::ALL.into_iter().find(|value| value.as_str() == name)",
    "    }",
    "",
    "    /// Returns everything the registry fixes about this predicate.",
    "    #[must_use]",
    "    pub const fn descriptor(self) -> &'static PredicateDescriptor {",
    "        &PREDICATE_REGISTRY[self as usize]",
    "    }",
    "}",
    "",
    "/// The registry itself, indexed by [`PredicateName`].",
    "///",
    "/// The layout below is the generator's, not rustfmt's, so that a byte",
    "/// comparison against a fresh render is the whole drift check.",
    "#[rustfmt::skip]",
    `pub const PREDICATE_REGISTRY: [PredicateDescriptor; ${names.length}] = [`,
    ...registry.predicates.flatMap((entry) => comma(indent(descriptorLines(entry), 4))),
    "];",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[2] === "--write") {
  const registry = await readRegistry();
  await writeFile(GENERATED_PATH, renderRustModule(registry), "utf8");
}
